#!/usr/bin/env python3

import hashlib
import json
import subprocess
import tempfile
from pathlib import Path


FIXTURE_DIR = Path(__file__).resolve().parent
ROOT = FIXTURE_DIR.parents[1]
UPSTREAM_FRAMES = (
    "block-128k",
    "empty-block",
    "rle-first-block",
    "zeroSeq_2B",
)


def run_zstd(zstd, *args):
    subprocess.run([str(zstd), *map(str, args)], check=True)


def frame_header(data):
    if data[:4] != bytes.fromhex("28 b5 2f fd") or len(data) < 5:
        raise ValueError("not a complete Zstandard frame")

    descriptor = data[4]
    single_segment = bool(descriptor & 0x20)
    dictionary_size = (0, 1, 2, 4)[descriptor & 0x03]
    content_size_flag = descriptor >> 6
    offset = 5

    if single_segment:
        window_size = None
    else:
        if offset >= len(data):
            raise ValueError("missing window descriptor")
        window_descriptor = data[offset]
        offset += 1
        window_log = 10 + (window_descriptor >> 3)
        window_base = 1 << window_log
        window_size = window_base + (window_base >> 3) * (window_descriptor & 0x07)

    dictionary_id = int.from_bytes(data[offset : offset + dictionary_size], "little")
    offset += dictionary_size

    if content_size_flag == 0:
        content_size_length = 1 if single_segment else 0
    else:
        content_size_length = (0, 2, 4, 8)[content_size_flag]
    if offset + content_size_length > len(data):
        raise ValueError("truncated frame header")
    if single_segment:
        content_size = int.from_bytes(data[offset : offset + content_size_length], "little")
        if content_size_flag == 1:
            content_size += 256
        window_size = content_size
    offset += content_size_length

    return dictionary_id, window_size, offset


def block_types(data, offset):
    result = []
    while True:
        if offset + 3 > len(data):
            raise ValueError("truncated block header")
        block_header = int.from_bytes(data[offset : offset + 3], "little")
        offset += 3
        last_block = bool(block_header & 1)
        block_type = (block_header >> 1) & 0x03
        block_size = block_header >> 3
        if block_type == 3:
            raise ValueError("reserved block type")
        result.append(block_type)
        offset += 1 if block_type == 1 else block_size
        if offset > len(data):
            raise ValueError("truncated block payload")
        if last_block:
            return result


def publish(generated):
    for name, source in generated.items():
        destination = FIXTURE_DIR / name
        content = source.read_bytes()
        if destination.exists():
            if destination.read_bytes() != content:
                raise SystemExit(f"{name} differs from the generated bytes; leaving it unchanged")
        else:
            destination.write_bytes(content)
        destination.chmod(0o644)


def main():
    lock = json.loads((ROOT / "flake.lock").read_text())
    nixpkgs_revision = lock["nodes"]["nixpkgs"]["locked"]["rev"]
    package = f"github:NixOS/nixpkgs/{nixpkgs_revision}#zstd"
    build = subprocess.run(
        ["nix", "build", "--no-link", "--no-write-lock-file", "--print-out-paths", package],
        check=True,
        capture_output=True,
        text=True,
    )
    store_paths = [Path(path) for path in build.stdout.splitlines()]
    zstd_candidates = [path / "bin" / "zstd" for path in store_paths if (path / "bin" / "zstd").is_file()]
    if len(zstd_candidates) != 1:
        raise SystemExit("expected one Nix output to contain the zstd executable")
    zstd = zstd_candidates[0]
    version = subprocess.run([str(zstd), "--version"], check=True, capture_output=True, text=True)
    print((version.stdout + version.stderr).strip())
    print(f"nixpkgs revision: {nixpkgs_revision}")

    generated = {}
    with tempfile.TemporaryDirectory(prefix=".generate-", dir=FIXTURE_DIR) as temp_dir:
        work = Path(temp_dir)

        plain = work / "plain.txt"
        plain.write_bytes(b"Plain Zstandard fixture from the pinned Nix CLI.\n")
        run_zstd(zstd, "-q", "-f", "-3", "--check", "-o", work / "plain.zst", plain)
        generated["plain.txt"] = plain
        generated["plain.zst"] = work / "plain.zst"

        checksum = work / "checksum.txt"
        checksum.write_bytes(b"Zstandard frame with an XXH64 content checksum.\n")
        run_zstd(zstd, "-q", "-f", "-3", "--check", "-o", work / "checksum.zst", checksum)
        generated["checksum.txt"] = checksum
        generated["checksum.zst"] = work / "checksum.zst"

        empty = work / "empty.txt"
        empty.write_bytes(b"")
        run_zstd(zstd, "-q", "-f", "--check", "-o", work / "empty.zst", empty)
        generated["empty.txt"] = empty
        generated["empty.zst"] = work / "empty.zst"

        rle = work / "rle-256k.bin"
        rle.write_bytes(b"R" * (256 * 1024))
        run_zstd(zstd, "-q", "-f", "-3", "--check", "-o", work / "rle-256k.zst", rle)
        _, _, rle_header_end = frame_header((work / "rle-256k.zst").read_bytes())
        if 1 not in block_types((work / "rle-256k.zst").read_bytes(), rle_header_end):
            raise SystemExit("zstd CLI did not generate an RLE block for rle-256k.bin")
        generated["rle-256k.bin"] = rle
        generated["rle-256k.zst"] = work / "rle-256k.zst"

        raw_multiblock = work / "raw-multiblock.bin"
        raw_multiblock.write_bytes(
            hashlib.shake_256(b"cl-deflate-kit raw Zstandard blocks v1").digest(384 * 1024)
        )
        run_zstd(
            zstd,
            "-q",
            "-f",
            "-3",
            "--check",
            "-o",
            work / "raw-multiblock.zst",
            raw_multiblock,
        )
        _, _, raw_header_end = frame_header((work / "raw-multiblock.zst").read_bytes())
        raw_types = block_types((work / "raw-multiblock.zst").read_bytes(), raw_header_end)
        if raw_types.count(0) < 2:
            raise SystemExit("zstd CLI did not generate multiple raw blocks")
        generated["raw-multiblock.bin"] = raw_multiblock
        generated["raw-multiblock.zst"] = work / "raw-multiblock.zst"

        first_frame = work / "first-frame.txt"
        second_frame = work / "second-frame.txt"
        first_frame.write_bytes(b"First concatenated frame.\n")
        second_frame.write_bytes(b"Second concatenated frame.\n")
        run_zstd(zstd, "-q", "-f", "-3", "--check", "-o", work / "first-frame.zst", first_frame)
        run_zstd(zstd, "-q", "-f", "-3", "--check", "-o", work / "second-frame.zst", second_frame)
        (work / "multiframe.zst").write_bytes(
            (work / "first-frame.zst").read_bytes() + (work / "second-frame.zst").read_bytes()
        )
        (work / "multiframe.bin").write_bytes(first_frame.read_bytes() + second_frame.read_bytes())
        generated["multiframe.bin"] = work / "multiframe.bin"
        generated["multiframe.zst"] = work / "multiframe.zst"

        window_input = work / "window-9m.bin"
        window_input.write_bytes(b"W" * (9 * 1024 * 1024))
        run_zstd(
            zstd,
            "-q",
            "-f",
            "-3",
            "--long=24",
            "--check",
            "-o",
            work / "window-9m.zst",
            window_input,
        )
        _, window_size, _ = frame_header((work / "window-9m.zst").read_bytes())
        if window_size <= 8 * 1024 * 1024:
            raise SystemExit(f"window-9m.zst declares only {window_size} bytes")
        generated["window-9m.zst"] = work / "window-9m.zst"

        dictionary_samples = []
        for sample_index in range(64):
            sample = work / f"dictionary-sample-{sample_index:02}.txt"
            lines = [
                f"tenant={sample_index:03};event={record:03};method=GET;path=/items/{record % 16};status=200\n"
                for record in range(128)
            ]
            sample.write_text("".join(lines))
            dictionary_samples.append(sample)
        dictionary = work / "dictionary.dict"
        run_zstd(
            zstd,
            "-q",
            "--train",
            "--dictID=12345",
            "--maxdict=4096",
            "-o",
            dictionary,
            *dictionary_samples,
        )
        dictionary_input = work / "dictionary-input.txt"
        dictionary_input.write_bytes(
            b"tenant=007;event=127;method=GET;path=/items/15;status=200\n" * 128
        )
        run_zstd(
            zstd,
            "-q",
            "-f",
            "-3",
            "--check",
            "-D",
            dictionary,
            "-o",
            work / "dictionary-id-12345.zst",
            dictionary_input,
        )
        dictionary_id, _, _ = frame_header((work / "dictionary-id-12345.zst").read_bytes())
        if dictionary_id != 12345:
            raise SystemExit(f"dictionary-id-12345.zst declares ID {dictionary_id}")
        generated["dictionary-id-12345.zst"] = work / "dictionary-id-12345.zst"

        for name in UPSTREAM_FRAMES:
            source = FIXTURE_DIR / f"{name}.zst"
            expected = work / f"{name}.bin"
            run_zstd(zstd, "-q", "-d", "-f", "-o", expected, source)
            generated[f"{name}.bin"] = expected

        for name in (
            "plain.zst",
            "checksum.zst",
            "empty.zst",
            "rle-256k.zst",
            "raw-multiblock.zst",
            "multiframe.zst",
            "window-9m.zst",
        ):
            run_zstd(zstd, "-q", "-t", work / name)
        run_zstd(zstd, "-q", "-D", dictionary, "-t", work / "dictionary-id-12345.zst")

        publish(generated)

    print(f"generated or confirmed {len(generated)} files")


if __name__ == "__main__":
    main()
